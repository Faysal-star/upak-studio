/** Rows for a printable ASCII char; unknown chars fall back to '?'. */
export function glyphRows(ch: string): readonly string[] {
  return FONT[ch] ?? FONT["?"];
}

/** True when every char of `text` has a real glyph (ASCII 32..126). */
export function hasGlyphs(text: string): boolean {
  for (const ch of text) if (!FONT[ch]) return false;
  return true;
}

/** Pixel size of `text` at integer `scale` (single line). */
export function measurePixelText(text: string, scale = 1): { w: number; h: number } {
  const n = text.length;
  if (n === 0) return { w: 0, h: 0 };
  return { w: (n * GLYPH_ADVANCE - 1) * scale, h: GLYPH_H * scale };
}

/**
 * Draw `text` into an RGBA buffer at (x, y) = top-left, integer `scale`,
 * replacing pixels (no blending) like every other raster op. Out-of-bounds
 * pixels are clipped.
 */
export function drawPixelText(
  buf: Uint8ClampedArray,
  bw: number,
  bh: number,
  x: number,
  y: number,
  text: string,
  scale: number,
  c: RGBA
): void {
  const s = Math.max(1, Math.round(scale));
  let cx = x;
  for (const ch of text) {
    const rows = glyphRows(ch);
    for (let gy = 0; gy < GLYPH_H; gy++) {
      const row = rows[gy];
      for (let gx = 0; gx < GLYPH_W; gx++) {
        if (row[gx] !== "#") continue;
        for (let sy = 0; sy < s; sy++) {
          const py = y + gy * s + sy;
          if (py < 0 || py >= bh) continue;
          for (let sx = 0; sx < s; sx++) {
            const px = cx + gx * s + sx;
            if (px < 0 || px >= bw) continue;
            const o = (py * bw + px) * 4;
            buf[o] = c[0];
            buf[o + 1] = c[1];
            buf[o + 2] = c[2];
            buf[o + 3] = c[3];
          }
        }
      }
    }
    cx += GLYPH_ADVANCE * s;
  }
}
